# 입력값에서 떼어낼 분량 표현 (예: "계란 2개", "돼지고기 300g")
_AMOUNT_PATTERN = re.compile(
    r"\d+(\.\d+)?\s*(kg|g|ml|l|개|알|장|모|대|줌|컵|봉|봉지|캔|쪽|단|마리|인분|공기|큰술|작은술|스푼|톨|통)?",
    re.IGNORECASE,
)

# 입력 구분자: 쉼표, 줄바꿈, 세미콜론, 슬래시, 가운뎃점
_SPLIT_PATTERN = re.compile(r"[,\n;/·|]+")


def normalize(name):
    """재료 이름 하나를 표준 이름으로 바꾼다.

    공백/분량/괄호를 제거하고 별칭 표를 조회한다.
    표에 없는 재료는 정리된 형태 그대로 돌려준다.
    """
    if not name:
        return ""

    cleaned = str(name).strip()
    cleaned = re.sub(r"\([^)]*\)", "", cleaned)   # 괄호 설명 제거
    cleaned = _AMOUNT_PATTERN.sub("", cleaned)    # 분량 제거
    cleaned = re.sub(r"\s+", "", cleaned)         # 모든 공백 제거
    cleaned = cleaned.strip("-~.·")

    if not cleaned:
        return ""

    if cleaned in _ALIAS_TO_CANONICAL:
        return _ALIAS_TO_CANONICAL[cleaned]

    # "볶음용돼지고기"처럼 별칭이 포함된 긴 이름도 잡아낸다.
    # 짧은 별칭이 엉뚱하게 걸리지 않도록 긴 별칭부터 검사한다.
    for alias in sorted(_ALIAS_TO_CANONICAL, key=len, reverse=True):
        if len(alias) >= 2 and alias in cleaned:
            return _ALIAS_TO_CANONICAL[alias]

    return cleaned


def parse_input(text):
    """사용자가 입력한 재료 문자열을 표준 이름 목록으로 변환한다.

    "김치, 밥 1공기\n계란 2개" -> ["김치", "밥", "계란"]
    중복은 제거하되 입력 순서는 유지한다.
    """
    if not text:
        return []

    if isinstance(text, (list, tuple, set)):
        raw_items = list(text)
    else:
        raw_items = _SPLIT_PATTERN.split(str(text))

    result = []
    for item in raw_items:
        # 쉼표 없이 띄어쓰기로만 나열한 경우도 처리 ("김치 밥 계란")
        for piece in item.split():
            canonical = normalize(piece)
            if canonical and canonical not in result:
                result.append(canonical)
    return result


def known_ingredients():
    """자동완성에 쓸 표준 재료 이름 목록 (가나다순)."""
    return sorted(ALIASES.keys())


def suggest_substitutes(missing_name, pantry):
    """없는 재료를 가진 재료로 대체할 수 있으면 그 목록을 돌려준다."""
    candidates = SUBSTITUTES.get(missing_name, [])
    return [c for c in candidates if c in pantry]
